#!/bin/sh
set -eu
# Initialization only. Group roles own no objects; each runtime LOGIN has one group.
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" -v ON_ERROR_STOP=1 \
  -v api_password="$DB_API_PASSWORD" -v auth_password="$DB_AUTH_PASSWORD" -v worker_password="$DB_WORKER_PASSWORD" <<'SQL'
CREATE ROLE talde_api NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE talde_auth NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE talde_worker NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
SELECT format('CREATE ROLE talde_api_login LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS', :'api_password') \gexec
SELECT format('CREATE ROLE talde_auth_login LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS', :'auth_password') \gexec
SELECT format('CREATE ROLE talde_worker_login LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS', :'worker_password') \gexec
GRANT talde_api TO talde_api_login;
GRANT talde_auth TO talde_auth_login;
GRANT talde_worker TO talde_worker_login;
SQL
